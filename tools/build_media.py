"""Regenerate christiane-buchmann/inc/media.php: image sizes, video poster thumbnails and durations.
Run after adding images or videos to inc/projects.php:
    python3 tools/build_media.py
"""
import hashlib
import json
import os
import subprocess
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
THEME = os.path.join(ROOT, "christiane-buchmann")
LIVE = "http://christianebuchmann.com"
CACHE = "/tmp/cb-media-cache"


def projects():
    out = subprocess.check_output(["php", "-r", 'echo json_encode(require "%s/inc/projects.php");' % THEME])
    return json.loads(out)


def image_size(path):
    os.makedirs(CACHE, exist_ok=True)
    if path.startswith("images/"):
        local = os.path.join(THEME, path)
    else:
        local = os.path.join(CACHE, hashlib.md5(path.encode()).hexdigest())
    if not os.path.exists(local):
        urllib.request.urlretrieve(LIVE + urllib.parse.quote(path), local)
    info = subprocess.check_output(["sips", "-g", "pixelWidth", "-g", "pixelHeight", local]).decode()
    w = int(info.split("pixelWidth:")[1].split()[0])
    h = int(info.split("pixelHeight:")[1].split()[0])
    return [w, h]


def video_info(video):
    """(poster image, duration in seconds or None)"""
    if video["provider"] == "youtube":
        hd = "https://i.ytimg.com/vi/%s/maxresdefault.jpg" % video["id"]
        try:
            urllib.request.urlopen(hd).close()
            return hd, None
        except Exception:
            return "https://i.ytimg.com/vi/%s/hqdefault.jpg" % video["id"], None
    url = "https://vimeo.com/api/oembed.json?width=1280&url=" + urllib.parse.quote("https://vimeo.com/" + video["id"])
    with urllib.request.urlopen(url) as r:
        data = json.load(r)
    return data["thumbnail_url"], data.get("duration")


def php(value):
    return json.dumps(value, ensure_ascii=False).replace("\\/", "/").replace("'", "\\'").replace('"', "'")


def main():
    sizes, thumbs, durations = {}, {}, {}
    for p in projects():
        for path in [p["image"]] + [g["src"] for g in p["gallery"]]:
            if path and path not in sizes:
                try:
                    sizes[path] = image_size(path)
                except Exception as e:
                    print("size failed", path, e)
        for v in p["videos"]:
            key = v["provider"] + ":" + v["id"]
            if key not in thumbs:
                try:
                    thumbs[key], duration = video_info(v)
                    if duration:
                        durations[key] = int(duration)
                except Exception as e:
                    print("thumbnail failed", key, e)
    lines = ["<?php", "// Generated by tools/build_media.py: image sizes (width, height) and video poster images.", "", "return array(", "    'sizes' => array("]
    lines += ["        %s => array(%d, %d)," % (php(k), w, h) for k, (w, h) in sorted(sizes.items())]
    lines += ["    ),", "    'thumbs' => array("]
    lines += ["        %s => %s," % (php(k), php(v)) for k, v in sorted(thumbs.items())]
    lines += ["    ),", "    'durations' => array("]
    lines += ["        %s => %d," % (php(k), v) for k, v in sorted(durations.items())]
    lines += ["    ),", ");", ""]
    open(os.path.join(THEME, "inc", "media.php"), "w").write("\n".join(lines))
    print("sizes:", len(sizes), "thumbs:", len(thumbs), "durations:", len(durations))


if __name__ == "__main__":
    main()
